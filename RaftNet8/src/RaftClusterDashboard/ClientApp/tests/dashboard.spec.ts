import { test, expect } from '@playwright/test';
import fs from 'node:fs';

type Settings = { Url: string; Password: string; PeerBasePort?: number; ClientBasePort?: number; ManagementBasePort?: number };
const settingsPath = process.env.RAFT_DASHBOARD_TEST_SETTINGS;
if (!settingsPath) throw new Error('Set RAFT_DASHBOARD_TEST_SETTINGS to the isolated stand settings file.');
const settings = JSON.parse(fs.readFileSync(settingsPath, 'utf8').replace(/^\uFEFF/, '')) as Settings;

test('real cluster login, live topology, entity settings, language and responsive themes', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(settings.Url);
  await page.getByLabel('Имя пользователя').fill('admin');
  await page.getByLabel('Пароль', { exact: true }).fill(settings.Password);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Обзор кластера' })).toBeVisible();
  await expect(page.locator('.node-card')).toHaveCount(3, { timeout: 30_000 });
  await expect(page.locator('.stale-alert')).toHaveCount(0, { timeout: 30_000 });
  await expect(page.getByText(/msg\/s · Клиентский API: 4xx\/5xx:/)).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('overview-dark-ru.png'), fullPage: true });
  await page.getByRole('menuitem', { name: 'Entities' }).click();
  await page.getByRole('button', { name: 'Создать entity' }).click();
  const name = 'browser-' + Date.now();
  await page.getByLabel('Название', { exact: true }).fill(name);
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByRole('cell', { name, exact: true })).toBeVisible({ timeout: 20_000 });
  const row = page.getByRole('row').filter({ hasText: name });
  await row.getByRole('button', { name: 'Настроить', exact: true }).click();
  await page.getByRole('switch', { name: 'Приостановить новые публикации' }).click();
  await page.getByLabel('Квота логического объёма, байт').fill('1024');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(row.getByText('Приостановить новые публикации', { exact: true })).toBeVisible({ timeout: 20_000 });
  await page.getByRole('menuitem', { name: 'Обзор' }).click();
  await page.getByRole('button', { name: 'Светлая тема' }).click();
  await page.screenshot({ path: testInfo.outputPath('overview-light-ru.png'), fullPage: true });
  await page.getByRole('combobox', { name: 'Язык' }).click();
  await page.getByRole('combobox', { name: 'Язык' }).press('ArrowDown');
  await page.getByRole('combobox', { name: 'Язык' }).press('Enter');
  await expect(page.getByRole('heading', { name: 'Cluster overview' })).toBeVisible();
  await page.locator('main').click({ position: { x: 5, y: 5 } });
  await page.setViewportSize({ width: 430, height: 900 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('overview-mobile-en.png'), fullPage: true });
  expect(errors).toEqual([]);
});

test('tokens, durable snapshot/add, viewer permissions and SSE reconnect', async ({ page, browser }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(settings.Url);
  await page.getByLabel('Имя пользователя').fill('admin');
  await page.getByLabel('Пароль', { exact: true }).fill(settings.Password);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect.poll(() => page.locator('.node-card').count(), { timeout: 30_000 }).toBeGreaterThanOrEqual(3);
  const joining = await page.locator('.node-card').count() + 1;
  await page.getByRole('menuitem', { name: 'Токены клиентов' }).click();
  await page.getByRole('button', { name: 'Выдать токен', exact: true }).click();
  const tokenName = 'browser-token-' + Date.now();
  await page.getByLabel('Название', { exact: true }).fill(tokenName);
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByText('Сохраните секрет сейчас. Повторно получить его невозможно.')).toBeVisible();
  await page.keyboard.press('Escape');
  const tokenRow = page.getByRole('row').filter({ hasText: tokenName });
  await tokenRow.getByRole('button', { name: 'Изменить токен' }).click();
  await page.getByLabel('Названия entities (* — все)').fill('browser-only');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(tokenRow.getByRole('cell', { name: 'browser-only', exact: true })).toBeVisible();
  await tokenRow.getByRole('button', { name: 'Отозвать', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'OK', exact: true }).click();
  await expect(tokenRow.getByText('Отозван', { exact: true })).toBeVisible();
  await page.getByRole('menuitem', { name: 'Ноды', exact: false }).click();
  await page.getByRole('button', { name: /Добавить ноду$/ }).click();
  await page.getByLabel('ID ноды', { exact: true }).fill('n' + joining);
  await page.getByLabel('Адрес Raft peer').fill('127.0.0.1');
  await page.getByLabel('Порт Raft peer').fill(String((settings.PeerBasePort ?? 6101) + joining - 1));
  await page.getByLabel('Адрес клиентского API').fill(`http://127.0.0.1:${(settings.ClientBasePort ?? 7101) + joining - 1}/`);
  await page.getByLabel('Адрес management API').fill(`http://127.0.0.1:${(settings.ManagementBasePort ?? 7201) + joining - 1}/`);
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload(); // An accepted operation must survive losing the browser's in-process dialog state.
  await page.getByRole('menuitem', { name: 'Операции' }).click();
  await expect(page.getByRole('row').filter({ hasText: 'add n' + joining }).getByText('Completed', { exact: true })).toBeVisible({ timeout: 45_000 });
  await page.getByRole('menuitem', { name: 'Обзор' }).click();
  await expect(page.locator('.node-card')).toHaveCount(joining, { timeout: 30_000 });
  await page.getByRole('button', { name: 'Создать snapshot', exact: true }).first().click();
  await page.getByRole('dialog').getByRole('button', { name: 'Подтвердить', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Операции' }).click();
  await expect(page.getByRole('row').filter({ hasText: 'snapshot' }).first().getByText('Completed', { exact: true })).toBeVisible({ timeout: 45_000 });
  await page.context().setOffline(true);
  await expect(page.locator('.header').getByText('Переподключение потока событий')).toBeVisible({ timeout: 30_000 });
  await page.context().setOffline(false);
  await expect(page.locator('.header').getByText('Live', { exact: true })).toBeVisible({ timeout: 30_000 });
  await page.screenshot({ path: testInfo.outputPath('operations-reconnected.png'), fullPage: true });

  await page.getByRole('menuitem', { name: 'Пользователи' }).click();
  await page.getByRole('button', { name: 'Создать пользователя', exact: true }).click();
  const viewer = 'viewer-' + Date.now();
  await page.getByLabel('Имя пользователя', { exact: true }).fill(viewer);
  await page.getByLabel('Пароль', { exact: true }).fill(settings.Password);
  await page.getByLabel('Доступные кластеры').click();
  await page.getByLabel('Доступные кластеры').press('ArrowDown');
  await page.getByLabel('Доступные кластеры').press('Enter');
  await page.getByRole('dialog').getByText('Создать пользователя', { exact: true }).click();
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByRole('cell', { name: viewer, exact: true })).toBeVisible();
  const context = await browser.newContext();
  const readOnly = await context.newPage();
  await readOnly.goto(settings.Url);
  await readOnly.getByLabel('Имя пользователя').fill(viewer);
  await readOnly.getByLabel('Пароль', { exact: true }).fill(settings.Password);
  await readOnly.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(readOnly.getByRole('heading', { name: 'Обзор кластера' })).toBeVisible();
  await expect(readOnly.getByRole('menuitem', { name: 'Токены клиентов' })).toHaveCount(0);
  await expect(readOnly.getByRole('button', { name: 'Добавить ноду' })).toHaveCount(0);
  expect((await context.request.get(settings.Url + '/api/admin/users')).status()).toBe(403);
  await context.close();
  expect(errors).toEqual([]);
});
